; ============================================================
; CustomTI85.asm
;
; REFERENCE ONLY. This file is not assembled by the VB6 project.
; CustomRomBuilder.exe emits the bytecode directly and appends
; the 1024-byte monochrome image converted from a BMP file.
;
; Program layout:
;   - code starts at $0000
;   - 128x64 1-bpp image data starts at $0056
;   - image data is copied to the LCD buffer at $FC00
;   - ON toggles the LCD on/off
; ============================================================

        ORG     $0000
START:
        DI
        LD      SP,$F000

        ; Video RAM is $FC00 (port 0 = $3C).
        LD      A,$3C
        OUT     ($00),A

        ; Contrast 18/32, also used by the LCD renderer.
        LD      A,$12
        OUT     ($02),A
        LD      ($8007),A

        ; LCD on. Power state 1 means "display is on".
        LD      A,$08
        OUT     ($03),A
        LD      A,$01
        LD      ($8000),A

        CALL    SHOW

MAIN:
        CALL    WAIT_RELEASE
        CALL    WAIT_PRESS
        CALL    WAIT_RELEASE

        LD      A,($8000)
        XOR     $01
        LD      ($8000),A
        JR      Z,POWER_OFF

        ; Power on: enable the LCD and redraw the image.
        LD      A,$08
        OUT     ($03),A
        CALL    SHOW
        JR      MAIN

POWER_OFF:
        ; Power off: disable the LCD and keep polling ON.
        XOR     A
        OUT     ($03),A
        JR      MAIN

WAIT_PRESS:
        IN      A,($03)
        AND     $08
        JR      NZ,WAIT_PRESS
        RET

WAIT_RELEASE:
        IN      A,($03)
        AND     $08
        JR      Z,WAIT_RELEASE
        RET

; ------------------------------------------------------------
; Copy the 1024-byte image from ROM to the LCD buffer.
; ------------------------------------------------------------
SHOW:
        LD      HL,IMAGE
        LD      DE,$FC00
        LD      BC,$0400
        LDIR
        RET

; ------------------------------------------------------------
; 128x64, 16 bytes per row, bit 7 is the leftmost pixel.
; The VB6 builder places its generated image bytes here.
; ------------------------------------------------------------
IMAGE:
        ; generated by CustomRomBuilder.exe (1024 bytes)

        END
